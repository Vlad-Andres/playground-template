import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { z } from "zod";
import { blockExamples } from "../../core/examples";
import { blockSchema } from "../../core/schema";
import { generatorWidgetTypes, widgetCatalogue, type WidgetType } from "../../core/widgets";

type JsonSchema = {
  type?: string | string[];
  enum?: unknown[];
  const?: unknown;
  anyOf?: JsonSchema[];
  oneOf?: JsonSchema[];
  items?: JsonSchema;
  properties?: Record<string, JsonSchema>;
  required?: string[];
  minItems?: number;
  maxItems?: number;
  minimum?: number;
  maximum?: number;
  pattern?: string;
  minLength?: number;
};

const HEADER = "<!-- Generated by `npm run docs:reference` from core/. Do not edit by hand. -->\n\n";

function typeOf(schema: JsonSchema): string {
  if (schema.const !== undefined) return `\`${JSON.stringify(schema.const)}\``;
  if (schema.enum) return schema.enum.map((value) => `\`${JSON.stringify(value)}\``).join(" \\| ");
  const variants = schema.anyOf ?? schema.oneOf;
  if (variants) return variants.map(typeOf).join(" \\| ");
  if (schema.type === "array") {
    const bounds =
      schema.minItems !== undefined || schema.maxItems !== undefined
        ? ` (${schema.minItems ?? 0}–${schema.maxItems ?? "∞"})`
        : "";
    return `array of ${schema.items ? typeOf(schema.items) : "any"}${bounds}`;
  }
  if (schema.type === "object") return "object";
  const type = Array.isArray(schema.type) ? schema.type.join(" \\| ") : (schema.type ?? "any");
  const extra: string[] = [];
  if (schema.minimum !== undefined) extra.push(`≥ ${schema.minimum}`);
  if (schema.maximum !== undefined) extra.push(`≤ ${schema.maximum}`);
  if (schema.pattern) extra.push(`pattern \`${schema.pattern}\``);
  return extra.length ? `${type} (${extra.join(", ")})` : type;
}

function fieldRows(schema: JsonSchema, prefix = ""): string[] {
  const required = new Set(schema.required ?? []);
  return Object.entries(schema.properties ?? {}).flatMap(([name, field]) => {
    const key = `${prefix}${name}`;
    const row = `| \`${key}\` | ${typeOf(field)} | ${required.has(name) ? "yes" : "no"} |`;
    const nested =
      field.type === "object" ? fieldRows(field, `${key}.`) : field.type === "array" && field.items?.type === "object" ? fieldRows(field.items, `${key}[].`) : [];
    return [row, ...nested];
  });
}

function fieldTable(schema: z.ZodType): string {
  const json = z.toJSONSchema(schema, { io: "input", unrepresentable: "any" }) as JsonSchema;
  return ["| Field | Type | Required |", "| --- | --- | --- |", ...fieldRows(json)].join("\n");
}

function blockPage(kind: keyof typeof blockExamples): string {
  const entry = blockExamples[kind];
  const schema = blockSchema.options.find((option) => option.shape.kind.value === kind);
  if (!schema) throw new Error(`No schema for block kind ${kind}`);
  return `${HEADER}# Block \`${kind}\`

**Use:** ${entry.use}

**Avoid:** ${entry.avoid}

## Example

\`\`\`json
${JSON.stringify(entry.example, null, 2)}
\`\`\`

## Fields

${fieldTable(schema)}

Every block may carry \`source\`: 1–5 \`{ "file", "page" }\` references to the material it came from.
`;
}

function widgetPage(type: WidgetType): string {
  const spec = widgetCatalogue[type];
  const block = { kind: "widget", type, title: spec.title, props: spec.example };
  return `${HEADER}# Widget \`${type}\` — ${spec.title}

**Pack:** ${spec.pack}

**When to use:** ${spec.description}

## Example block

\`\`\`json
${JSON.stringify(block, null, 2)}
\`\`\`

## Props

${fieldTable(spec.props)}

The validator also checks the cross-field rules (ids that must exist, lengths that must match,
expressions that must parse). Run \`npm run validate\` after writing a widget.
`;
}

const PACK_HINTS: Record<string, string> = {
  core: "Any subject.",
  math: "Formulas and functions (Math, physics, economics, CS performance).",
};

function widgetIndex(): string {
  const rows = generatorWidgetTypes.map(
    (type) => `| [\`${type}\`](${type}.md) | ${widgetCatalogue[type].pack} | ${widgetCatalogue[type].description} |`,
  );
  return `${HEADER}# Widget reference

Only these widgets may be used in generated courses. Each page has an example and a props table.

| Widget | Pack | When to use |
| --- | --- | --- |
${rows.join("\n")}

Packs: ${Object.entries(PACK_HINTS)
    .map(([pack, hint]) => `**${pack}** — ${hint}`)
    .join(" ")}

The \`dis\` pack holds course-specific labs of the Data-Intensive Systems example and is not for
new courses.
`;
}

function blockIndex(): string {
  const rows = Object.entries(blockExamples).map(([kind, entry]) => `| [\`${kind}\`](${kind}.md) | ${entry.use} |`);
  return `${HEADER}# Block reference

All blocks are strict JSON objects with a \`kind\`. The canonical schemas are in \`schema/\` and
\`core/schema.ts\`. Every block may carry \`source\` (1–5 \`{ "file", "page" }\`).

| Kind | Use |
| --- | --- |
${rows.join("\n")}

Prefer the smallest block that preserves the source's teaching purpose. Never use a widget as a
decoration and never put executable course logic in JSON.
`;
}

/** Every generated reference file, keyed by path relative to the repository root. */
export function referenceDocuments(): Record<string, string> {
  const files: Record<string, string> = { "docs/agent/blocks/index.md": blockIndex(), "docs/agent/widgets/index.md": widgetIndex() };
  for (const kind of Object.keys(blockExamples) as (keyof typeof blockExamples)[]) files[`docs/agent/blocks/${kind}.md`] = blockPage(kind);
  for (const type of generatorWidgetTypes) files[`docs/agent/widgets/${type}.md`] = widgetPage(type);
  return files;
}

export function writeReferenceDocuments(root = "."): void {
  for (const [file, content] of Object.entries(referenceDocuments())) {
    const target = path.join(root, file);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, content);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeReferenceDocuments();
  console.log(`Wrote ${Object.keys(referenceDocuments()).length} reference files.`);
}
